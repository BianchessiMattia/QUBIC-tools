from qubic.lib.Instrument.Qinstrument import QubicInstrument
from qubic.lib.Qdictionary import qubicDict
from qubic.lib.Qscene import QubicScene
from qubic.lib.Qsamplings import QubicSampling
from qubicpack.qubicfp import qubicfp

    
def build_minimal_acquisition(sampling):
    """
    Build the minimal QubicInstrument, QubicScene and QubicAcquisition
    objects needed to generate a TOD from a given sky map, bypassing
    PipelineEnd2End / PipelineFrequencyMapMaking entirely.

    Parameters
    ----------
    d : dict
        QUBIC dictionary defining a single, fixed filter_nu (monochromatic
        instrument). MultiBand should be False here, since this builds a
        single QubicInstrument and not a QubicMultibandInstrument.
    sampling : QubicSampling
        Pointing already generated by the user, e.g. via a custom
        QubicScanScheduler strategy.

    Returns
    -------
    QubicAcquisition
        Acquisition object combining instrument, sampling and scene.
    """
    # Load QUBIC dictionary from file
    dictfilename = "td.dict"
    d = qubicDict()
    d.read_from_file(dictfilename)

    instrument = QubicInstrument(d)
    scene = QubicScene(d)
    acquisition = QubicAcquisition(instrument, sampling, scene, d)
    return acquisition


def get_tod_full_operator(acquisition, sky_map):
    """
    Generate the TOD using the full instrumental acquisition operator
    (detector response, filter, hwp, polarizer, projection, aperture,
    unit conversion, etc).

    Parameters
    ----------
    acquisition : QubicAcquisition
        Acquisition object built with build_minimal_acquisition.
    sky_map : ndarray
        Input sky map of shape (npix, 3).

    Returns
    -------
    ndarray
        Simulated TOD, shape (ndetectors, ntimes), in instrumental power
        units (W), after the full chain including unit conversion.
    """
    H = acquisition.get_operator()
    tod = H(sky_map)
    return tod


def get_tod_projection_only(acquisition, sky_map, interp_projection=False):
    """
    Generate the TOD using only the projection operator, i.e. the pure
    synthetic beam geometry combined with the scanning strategy, bypassing
    all other instrumental factors (filter, hwp, polarizer, aperture,
    response, unit conversion).

    Parameters
    ----------
    acquisition : QubicAcquisition
        Acquisition object built with build_minimal_acquisition.
    sky_map : ndarray
        Input sky map of shape (npix, 3).
    interp_projection : bool, optional
        Whether to use bilinear interpolation for the projection peaks,
        by default False.

    Returns
    -------
    ndarray
        Simulated TOD obtained from the projection operator alone, in the
        same units as the input sky map (no instrumental scaling applied).
    """
    projection = acquisition.instrument.get_projection_operator(
        acquisition.sampling,
        acquisition.scene,
        interp_projection=interp_projection,
    )
    tod = projection(sky_map)
    return tod


def build_constant_sky(scene, i_value=1.0, q_value=0.0, u_value=0.0):
    """
    Build a sky map constant over the whole sphere and over time, with
    user-specified I, Q, U values, matching the pixel ordering and shape
    convention used by QubicScene (RING ordering, columns ordered as I, Q, U).

    Parameters
    ----------
    scene : QubicScene
        Discretized scene, used to retrieve the number of HEALPix pixels
        via scene.npixel.
    i_value : float, optional
        Constant intensity value, by default 1.0
    q_value : float, optional
        Constant Q Stokes value, by default 0.0
    u_value : float, optional
        Constant U Stokes value, by default 0.0

    Returns
    -------
    ndarray
        Sky map of shape (npixel, 3), constant across the sphere.
    """
    sky_map = np.zeros((scene.npixel, 3))
    sky_map[:, 0] = i_value
    sky_map[:, 1] = q_value
    sky_map[:, 2] = u_value
    return sky_map
